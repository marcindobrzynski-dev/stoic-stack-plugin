// Pure prompt signals — everything the engine derives from raw prompt text.
//
// The UserPromptSubmit hook calls this module at write time and stores the
// results in the session event log; the Stop hook never recomputes them. Four
// judgments live here: how much thinking a prompt shows (prompt effort, the
// primary autopilot signal), whether the harness injected it (neutralized
// logging), whether it is a genuine question (question relief), and whether it
// is the plugin talking to itself (self-instrumentation guard).
//
// This module is Domain-layer pure: deterministic, no filesystem, no child
// processes, no environment reads. Every input arrives as an argument and any
// input shape is tolerated — a non-string prompt is judged as empty rather
// than thrown on, because these functions run inside fail-silent hooks.
//
// EVERY NUMBER AND WORD LIST IN THIS MODULE IS AN UNCALIBRATED PLACEHOLDER.
// The effort heuristic is deliberately crude — a handful of named regex
// predicates combined into one signed number — and deliberately isolated
// here so that replacing it (or any of its constants) never touches a caller:
// callers consume only the exported functions, never the sub-scores.
//
// Contract: thoughts/shared/.project/architecture/payloads.md
// §`Session event log` (prompt event: `effort`, `neutralized`, truncation).

/**
 * Stored prompt length bound, in characters. CONTRACT-BOUND, not a tunable
 * placeholder: payloads.md freezes prompt events at "text, truncated to 2000
 * chars", so changing this number is a payload-contract change that must land
 * in that document and its integration test together.
 */
export const PROMPT_TRUNCATION_CHARS = 2000;

/** The harness-injection marker Claude Code puts in machine-generated prompts. */
export const TASK_NOTIFICATION_MARKER = "<task-notification>";

/** The prefix of the plugin's own skill invocations. */
export const OWN_PROMPT_PREFIX = "/stoic-stack";

/**
 * At or below this many words a prompt reads as short. Uncalibrated
 * placeholder.
 */
export const SHORT_PROMPT_WORD_LIMIT = 8;

/**
 * At or above this many words a prompt's sheer length counts as one
 * specificity marker. Uncalibrated placeholder.
 */
export const LONG_PROMPT_WORD_LIMIT = 60;

/**
 * Minimum words in a question line before it earns relief — "ok?" is assent,
 * not visible thinking. Uncalibrated placeholder.
 */
export const QUESTION_MIN_WORDS = 3;

// ---------------------------------------------------------------------------
// Named predicates — one question each, so the heuristic reads as a checklist
// and no anonymous regex hides in the combination below. All placeholders.
// ---------------------------------------------------------------------------

/** Words that delegate wholesale without adding direction. Placeholder list. */
const VAGUE_COMMAND_WORDS = Object.freeze([
  "again",
  "continue",
  "fix",
  "go",
  "just",
  "ok",
  "okay",
  "proceed",
  "retry",
  "sure",
  "yes",
]);

/** Words that state a constraint — evidence of a held intention. Placeholder list. */
const CONSTRAINT_WORDS = Object.freeze([
  "always",
  "avoid",
  "constraint",
  "don't",
  "ensure",
  "keep",
  "must",
  "never",
  "only",
  "preserve",
  "should",
]);

const hasCodeFence = (text) => text.includes("```");

/** A path-like token: something/with/slashes or a dotted file name. */
const hasPathReference = (text) =>
  /(?:^|[\s"'`(])[\w.-]+[/\\][\w./\\-]+/.test(text) ||
  /\b[\w-]+\.[a-z]{2,4}\b/i.test(text);

const hasDigit = (text) => /\d/.test(text);

/** A bulleted or numbered line — the prompt carries visible structure. */
const hasStructuredList = (text) => /^\s*(?:[-*]|\d+[.)])\s+\S/m.test(text);

const wordsOf = (text) => text.split(/\s+/).filter((word) => word !== "");

const containsWordFrom = (words, list) =>
  list.some((entry) => words.includes(entry));

/** Coerce any input to judgeable text: strings pass, everything else is empty. */
const asText = (value) => (typeof value === "string" ? value : "");

/**
 * Is this prompt machine-generated by the harness (a task notification)
 * rather than typed by the user? Detection is by marker substring anywhere in
 * the text: real notifications wrap the marker in an envelope, so anchoring to
 * the start would miss them. A user pasting the literal marker is neutralized
 * too — an accepted cost, since neutralizing only zeroes one effort signal.
 *
 * @param {unknown} prompt - Raw prompt text from the hook payload.
 * @returns {boolean} True when the harness-injection marker is present.
 */
export function isHarnessInjection(prompt) {
  return asText(prompt).includes(TASK_NOTIFICATION_MARKER);
}

/**
 * Is this the plugin talking to itself — a `/stoic-stack` skill invocation?
 * The prefix must open the prompt as a whole token (`/stoic-stack`,
 * `/stoic-stack status`, `/stoic-stack:setup`), so a word that merely starts
 * with it, or a mention mid-sentence, is still the user's own prompt.
 *
 * @param {unknown} prompt - Raw prompt text from the hook payload.
 * @returns {boolean} True when observation should ignore this prompt.
 */
export function isOwnPluginPrompt(prompt) {
  const text = asText(prompt).trimStart();
  if (!text.startsWith(OWN_PROMPT_PREFIX)) {
    return false;
  }
  const next = text.charAt(OWN_PROMPT_PREFIX.length);
  return next === "" || /[\s:]/.test(next);
}

/**
 * Does this prompt ask a genuine question — visible thinking that earns the
 * turn its question relief? Crude placeholder rule: some line ends with `?`
 * and carries at least QUESTION_MIN_WORDS words, so bare assent ("ok?") does
 * not count. Harness injections and the plugin's own prompts never do.
 *
 * @param {unknown} prompt - Raw prompt text from the hook payload.
 * @returns {boolean} True when the turn should earn question relief.
 */
export function isGenuineQuestion(prompt) {
  const text = asText(prompt);
  if (text === "" || isHarnessInjection(text) || isOwnPluginPrompt(text)) {
    return false;
  }
  return text
    .split("\n")
    .some(
      (line) =>
        line.trimEnd().endsWith("?") &&
        wordsOf(line).length >= QUESTION_MIN_WORDS,
    );
}

// Sub-score sizes for the effort combination below. Uncalibrated placeholders:
// vagueness has two markers, specificity six, and effort is their difference
// as fractions — so one signal can never outvote the whole other side.
const VAGUENESS_MARKERS = 2;
const SPECIFICITY_MARKERS = 6;

/**
 * How much thinking does this prompt show? Returns a signed signal in
 * [-1, +1]: positive means low effort (short, vague — the autopilot pattern,
 * raising the score), negative means high effort (paths, code, numbers,
 * constraints, structure, length — visible thinking, lowering it). Empty,
 * non-string, and harness-injected prompts are exactly 0: no user thinking
 * happened, and none should be scored either way.
 *
 * The scale is a crude uncalibrated placeholder: count which named vagueness
 * and specificity markers fire, and subtract the fractions.
 *
 * @param {unknown} prompt - Raw prompt text from the hook payload.
 * @returns {number} Signed effort in [-1, +1]; low effort is positive.
 */
export function promptEffort(prompt) {
  const text = asText(prompt).trim();
  if (text === "" || isHarnessInjection(text)) {
    return 0;
  }

  const words = wordsOf(text.toLowerCase());
  const wordCount = words.length;

  const vagueness =
    (wordCount <= SHORT_PROMPT_WORD_LIMIT ? 1 : 0) +
    (containsWordFrom(words, VAGUE_COMMAND_WORDS) ? 1 : 0);

  const specificity =
    (hasCodeFence(text) ? 1 : 0) +
    (hasPathReference(text) ? 1 : 0) +
    (hasDigit(text) ? 1 : 0) +
    (containsWordFrom(words, CONSTRAINT_WORDS) ? 1 : 0) +
    (hasStructuredList(text) ? 1 : 0) +
    (wordCount >= LONG_PROMPT_WORD_LIMIT ? 1 : 0);

  const effort =
    vagueness / VAGUENESS_MARKERS - specificity / SPECIFICITY_MARKERS;
  return Math.max(-1, Math.min(1, effort));
}

/**
 * Bound a prompt to its stored length. The session log keeps the truncated
 * text (the classifier and the pause context both need it), never the full
 * prompt, so one enormous paste cannot bloat the log.
 *
 * @param {unknown} prompt - Raw prompt text from the hook payload.
 * @returns {string} At most PROMPT_TRUNCATION_CHARS characters; "" for
 *   non-strings.
 */
export function truncatePrompt(prompt) {
  return asText(prompt).slice(0, PROMPT_TRUNCATION_CHARS);
}
